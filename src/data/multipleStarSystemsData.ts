export interface MultipleStarComponent {
  id: string; // e.g. 'sirius-a'
  catalogStarId?: string; // Links to catalog star (e.g. 'vfts-352' for 'vfts-352-primary')
  name: string; // e.g. 'Sirius A'
  bayerDesignation?: string; // e.g. 'α CMa A'
  spectralType: string; // e.g. 'A1V'
  massSolar: number; // e.g. 2.06
  radiusSolar: number; // in Solar Radii
  temperature: number; // in Kelvin
  luminositySolar: number; // in L_sun
  colorHex: string;
  coronaColorHex: string;
  isPrimary?: boolean;
  isCompactRemnant?: boolean;
  isBlackHole?: boolean;
  hasAccretionDisk?: boolean;
  isContactBinaryPair?: boolean;
  rotationalPeriodDays?: number; // Stellar axial rotation period in Earth days
  rotationalPeriodHours?: number; // Rotation period in hours (for rapid rotators/contact binaries)
  rotationalPeriodFormatted?: string; // Formatted display label (e.g. "22.0 Days", "8.0 Hours")
  isTidallyLocked?: boolean;
  description: string;
}

export interface KeplerianOrbitData {
  primaryId: string;
  secondaryId: string;
  label: string;
  semiMajorAxisAU: number; // a in AU
  orbitalPeriodYears: number; // P in years
  orbitalPeriodDays?: number; // for rapid orbits
  eccentricity: number; // e
  inclinationDeg: number; // i in degrees
  ascendingNodeDeg: number; // Ω in degrees
  argPeriastronDeg: number; // ω in degrees
  periastronAU: number; // a * (1 - e)
  apastronAU: number; // a * (1 + e)
  epochOfPeriastron?: string;
  radialVelocityAmplitudeKmS?: number; // K1 + K2
  description: string;
  orbitsBarycenter?: boolean;
}

export interface MultipleStarSystemData {
  id: string;
  name: string;
  systemType: 'Visual Binary' | 'Astrometric Binary' | 'Spectroscopic Binary' | 'Hierarchical Triple' | 'Quadruple Hierarchy' | 'Sextuple Hierarchy' | 'Overcontact Binary' | 'High-Mass X-Ray Binary' | 'Colliding-Wind Binary';
  constellation: string;
  distanceLy: number;
  starIds: string[]; // IDs in the stellar catalog
  components: MultipleStarComponent[];
  orbits: KeplerianOrbitData[];
  barycenterDescription: string;
  astrophysicalSignificance: string;
  visualSeparationArcsec?: number;
  hasContactBinary?: boolean;
  effectiveStarCount?: number; // Contact binaries count as 1 star
}

/**
 * Computes the realistic effective star count for a multiple star system.
 * Contact binaries physically share an envelope and count as 1 star object,
 * while still detailing each component lobe on the stellar system overview.
 */
export function getEffectiveStarCount(system: MultipleStarSystemData): number {
  if (system.effectiveStarCount !== undefined) return system.effectiveStarCount;
  if (system.systemType === 'Overcontact Binary' || system.hasContactBinary) {
    const contactLobes = system.components.filter((c) => c.isContactBinaryPair).length;
    if (contactLobes >= 2) {
      return Math.max(1, system.components.length - contactLobes + 1);
    }
  }
  return system.components.length;
}

